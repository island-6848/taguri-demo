def draw_md(resolved):
    L = ["# 知識処理システム「たぐり」企画書 ── 7 枚版の台本", "",
         "- 対象タスク: [#000002 知識処理システム企画書の作成](../tasks/active/current/000002-system-proposal-document.md)",
         "- 下書き: [docs/000002-system-proposal-taguri.md](000002-system-proposal-taguri.md)",
         "- 出力: [000002-system-proposal-taguri-7p.pptx](000002-system-proposal-taguri-7p.pptx)"
         " / [プレビュー HTML](000002-system-proposal-taguri-7p.html)",
         "- 生成: `python3 tools/proposal/build_taguri_7p.py`（この台本・pptx・プレビューは"
         "**同じレイアウト定義から生成される**）", "",
         "配布フォーマットは **8 枚（表紙 / 目次 / 1〜3 章 各 1 枚 / 4 章 2 枚 / 5 章 1 枚）・4:3**、"
         "章スライドの本文領域は "
         "**9.06 × 5.72 inch**。1 枚に載る量の上限は 18pt で約 15 行（全角 36 字）＝ 540 字なので、"
         "**図のラベルとして 10pt 前後で組み、1 枚 500〜700 字に抑えている。**", "",
         "---", "", "## 1 枚目 表紙", "",
         "知識処理システム「たぐり」／企画書／2026/08／仲谷茉桜", "",
         "## 2 枚目 目次", "",
         "1. 知識処理システム概要 / 2. 処理対象知識概要 / 3. 対象ユーザ／利用シーン / "
         "4. システム効果 / 5. 実装言語／フレームワーク", "",
         "（**章名のみ。**各章 1 行の要旨はフォーマットに無いので足していない）", ""]
    for spec in resolved:
        L += ["---", "", f"## {spec['no']} 枚目 {spec['title']}", ""]
        for sh in spec["shapes"]:
            if sh["k"] == "claim":
                L += [f"> **{sh['text']}**", ""]
            elif sh["k"] == "label":
                L += [f"### {sh['text']}", ""]
            elif sh["k"] == "para":
                # bullets() は「・」始まりの para なので箇条書きに戻す
                lines = sh["text"].split("\n")
                if all(t.startswith("・") for t in lines):
                    L += [f"- {t[1:]}" for t in lines] + [""]
                else:
                    L += ["\n".join(lines), ""]
            elif sh["k"] == "dotgrid":
                L += [f"（点の格子 {sh['total']:,} 点のうち {sh['hi']} 点を強調"
                      + (f" ── {sh['note']}）" if sh["note"] else "）"), ""]
            elif sh["k"] == "bars":
                L += [f"- {lab} `{disp}`" for lab, _v, disp in sh["rows"]]
                if sh.get("lead"):
                    L += ["", f"**{sh['lead']}**"]
                if sh["note"]:
                    L.append(f"  <small>{sh['note']}</small>")
                L.append("")
            elif sh["k"] == "cycle":
                if sh["center"]:
                    L += [f"（中心: {sh['center']}）", ""]
                L += [f"{'①②③④'[i]} **{t}** ── {b}" for i, (t, b) in enumerate(sh["nodes"])]
                L += ["（④ から ① に戻り、循環する）", ""]
            elif sh["k"] == "table":
                L.append("| " + " | ".join(sh["cols"]) + " |")
                L.append("|" + "---|" * len(sh["cols"]))
                L += ["| " + " | ".join(r) + " |" for r in sh["rows"]]
                L.append("")
            elif sh["k"] == "loopback":
                L += [f"（↑ {sh['note']}）", ""]
            elif sh["k"] == "arrow":
                # md には矢印の図が無いので、注記を「↓」の行として残す
                mark = {"right": "→", "up": "↑"}.get(sh.get("dirn"), "↓")
                L += [f"（{mark} {sh['note']}）" if sh.get("note") else f"（{mark}）", ""]
            elif sh["k"] == "src":
                L += [f"<small>{sh['text']}</small>", ""]
            elif sh["k"] == "card":
                head = f"**{sh['t']}**"
                if sh.get("num"):
                    head = f"`{sh['num']}` {head}"
                L.append(f"- {head}")
                if sh.get("b"):
                    for line in sh["b"].split("\n"):
                        L.append(f"  - {line}")
        L.append("")
    L += ["---", "", "## 参考資料（8 枚目以降・フォーマット外）", ""]
    L += [f"{i}. {a}" for i, a in enumerate(APPENDIX, 1)]
    L += ["", "7 枚に収めるために本文から外したもの。**質疑で出す前提で、詳細版から切り出す。**",
          "とくに 1 のクチコミ密度は「なぜ公演ではなく人を単位にするのか」の裏づけなので、"
          "**本文に数字 1 行を残し、図は参考資料に置いて口頭で補う。**", ""]
    OUT_MD.write_text("\n".join(L), encoding="utf-8")


