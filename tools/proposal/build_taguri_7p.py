# ── HTML プレビュー出力（同じ座標を % に変換）────────────────────────
def esc(s: str) -> str:
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            .replace("\n", "<br>"))


def html_shape(sh: dict) -> str:
    X, Y = AREA_X + sh["x"], AREA_Y + sh["y"]
    pos = (f'left:{X / 10 * 100:.3f}%;top:{Y / 7.5 * 100:.3f}%;'
           f'width:{sh["w"] / 10 * 100:.3f}%;height:{sh["h"] / 7.5 * 100:.3f}%')
    k = sh["k"]
    if k == "claim":
        return (f'<div class="s claim" style="{pos}"><span style="--pt:{sh.get("pt",13)}">'
                f'{esc(sh["text"])}</span></div>')
    if k in ("label", "src"):
        pt = sh.get("pt", 9 if k == "src" else 9.5)
        return f'<div class="s {k}" style="{pos};--pt:{pt}">{esc(sh["text"])}</div>'
    if k == "para":
        return (f'<div class="s para" style="{pos};--pt:{sh.get("pt",10.5)}">'
                f'{esc(sh["text"])}</div>')
    if k == "group":
        return (f'<div class="s group" style="{pos}">'
                f'<b class="gt">{esc(sh["title"])}</b></div>')
    if k == "card":
        out = [f'<div class="s card {sh["style"]}" style="{pos}">']
        if sh.get("num"):
            out.append(f'<b class="num">{esc(sh["num"])}</b>')
        out.append(f'<b class="t" style="--pt:{sh["tpt"]}">{esc(sh["t"])}</b>')
        if sh.get("b"):
            out.append(f'<span class="b" style="--pt:{sh["bpt"]}">{esc(sh["b"])}</span>')
        out.append("</div>")
        return "".join(out)
    if k == "arrow":
        cls = {"right": "arw right", "up": "arw up"}.get(sh.get("dirn"), "arw down")
        note = (f'<i style="--pt:8.5">{esc(sh["note"])}</i>') if sh.get("note") else ""
        return f'<div class="s {cls}" style="{pos}"><u></u>{note}</div>'
    if k == "dotgrid":
        cells = "".join(f'<i class="{"on" if i < sh["hi"] else ""}"></i>'
                        for i in range(sh["total"]))
        note = f'<b>{esc(sh["note"])}</b>' if sh["note"] else ""
        return (f'<div class="s dots" style="{pos};'
                f'--cols:{sh["cols"]};--dot:{sh["dot"] / 10 * 100:.3f}">'
                f'<u>{cells}</u>{note}</div>')
    if k == "bars":
        base = sh.get("baseline", True)
        top = max(v for _, v, _ in sh["rows"])
        rows = "".join(
            f'<tr><th>{esc(lab)}</th><td><u style="width:{max(1.2, v / top * 100):.1f}%"'
            f' class="{"" if base and not i else "on"}"></u></td>'
            f'<td class="v">{esc(disp)}</td></tr>'
            for i, (lab, v, disp) in enumerate(sh["rows"]))
        note = f'<b>{esc(sh["note"])}</b>' if sh["note"] else ""
        lead = (f'<em style="--lpt:{LEAD_PT}">{esc(sh["lead"])}</em>'
                if sh.get("lead") else "")
        return (f'<div class="s bars{"" if base else " flat"}" style="{pos};--pt:{sh["pt"]}">'
                f'<table>{rows}</table>{lead}{note}</div>')
    if k == "table":
        cols = "".join(f'<col style="width:{cw / sh["w"] * 100:.2f}%">'
                       for cw in sh["colw"])
        head = "".join(f"<th>{esc(c)}</th>" for c in sh["cols"])
        body = "".join("<tr>" + "".join(f"<td>{esc(c)}</td>" for c in r) + "</tr>"
                       for r in sh["rows"])
        return (f'<div class="s tbl" style="{pos};--pt:{sh["pt"]}">'
                f'<table><colgroup>{cols}</colgroup>'
                f'<thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>')
    if k == "cycle":
        nw, nh, ch = sh["nw"], sh["nh"], sh["h"]
        eh = 1.30 if sh["entry"] else 0.0
        tot = sh["h"] + eh
        rw = sh["ring_w"] or sh["w"]
        rxp = rw / sh["w"] * 100 / 2 - nw / sh["w"] * 100 / 2
        ryp = (ch - nh) / tot * 100 / 2
        cyp = (eh + ch / 2) / tot * 100
        parts = []
        if sh["entry"]:
            boxes = sh["entry"]
            n = len(boxes)
            bwin = (7.90 - 0.40 * (n - 1)) / n
            bwp = bwin / sh["w"] * 100
            gp = 0.40 / sh["w"] * 100
            span = 7.90 / sh["w"] * 100
            for bi, (et, eb) in enumerate(boxes):
                lx = 50 - span / 2 + bi * (bwp + gp) + bwp / 2
                cls = "ent" if bi == 0 else "ent alt"
                parts.append(f'<b class="{cls}" style="left:{lx:.2f}%;'
                             f'top:{0.36 / tot * 100:.2f}%;width:{bwp:.2f}%;'
                             f'height:{0.72 / tot * 100:.2f}%">'
                             f'<s>{esc(et)}</s><em>{esc(eb)}</em></b>')
                if n > 1:
                    parts.append(f'<i class="stem" style="left:{lx:.2f}%;'
                                 f'top:{0.72 / tot * 100:.2f}%;'
                                 f'height:{0.22 / tot * 100:.2f}%"></i>')
            if n > 1:
                x0 = 50 - span / 2 + bwp / 2
                x1 = 50 + span / 2 - bwp / 2
                parts.append(f'<i class="join" style="left:{x0:.2f}%;'
                             f'top:{0.94 / tot * 100:.2f}%;width:{x1 - x0:.2f}%"></i>')
            parts.append(f'<i class="down" style="left:50%;'
                         f'top:{0.94 / tot * 100:.2f}%;height:{0.26 / tot * 100:.2f}%"></i>')
        parts.append(f'<u style="left:{50 - rxp:.2f}%;top:{cyp - ryp:.2f}%;'
                     f'width:{rxp * 2:.2f}%;height:{ryp * 2:.2f}%"></u>')
        for i, (title, body) in enumerate(sh["nodes"]):
            a = math.radians(i * 90)
            parts.append(f'<b style="left:{50 + rxp * math.sin(a):.2f}%;'
                         f'top:{cyp - ryp * math.cos(a):.2f}%;'
                         f'width:{nw / sh["w"] * 100:.2f}%;height:{nh / tot * 100:.2f}%">'
                         f'<s>{"①②③④"[i]} {esc(title)}</s><em>{esc(body)}</em></b>')
        for ang, rot in ((45, 135), (135, 225), (225, 315), (315, 45)):
            a = math.radians(ang)
            parts.append(f'<i class="dir" style="left:{50 + rxp * math.sin(a):.2f}%;'
                         f'top:{cyp - ryp * math.cos(a):.2f}%;--rot:{rot}deg"></i>')
        if sh["interlude"]:
            it_, ib = sh["interlude"]
            a = math.radians(315)
            parts.append(f'<b class="itl" style="left:{50 + rxp * 1.30 * math.sin(a):.2f}%;'
                         f'top:{cyp - ryp * 1.30 * math.cos(a):.2f}%;'
                         f'width:{1.70 / sh["w"] * 100:.2f}%;height:{0.58 / tot * 100:.2f}%">'
                         f'<s>{esc(it_)}</s><em>{esc(ib)}</em></b>')
        if sh["center"]:
            parts.append(f'<i class="ctr" style="top:{cyp:.2f}%">{esc(sh["center"])}</i>')
        note = f'<span class="nt">{esc(sh["note"])}</span>' if sh["note"] else ""
        return f'<div class="s cyc" style="{pos}">{"".join(parts)}{note}</div>'
    if k == "loopback":
        return (f'<div class="s loopback" style="{pos}">'
                f'<i>{esc(sh["note"])}</i><u></u></div>')
    if k in ("fork", "join"):
        return f'<div class="s {k}" style="{pos}"><u></u><i></i><i></i></div>'
    return ""


