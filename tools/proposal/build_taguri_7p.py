def add_text(tf, runs, space_before=0.0):
    """runs: [(text, pt, bold, color)] を段落に流す。"""
    tf.word_wrap = True
    first = True
    for text, pt, bold, color in runs:
        for i, line in enumerate(text.split("\n")):
            p = tf.paragraphs[0] if first else tf.add_paragraph()
            first = False
            p.line_spacing = 1.28
            if space_before and i == 0:
                p.space_before = Pt(1.5)
            r = p.add_run()
            r.text = line
            r.font.size = Pt(pt)
            r.font.bold = bold
            r.font.name = FONT
            r.font.color.rgb = rgb(color)
            p.font.name = FONT


def draw_pptx(resolved):
    shutil.copy(TEMPLATE, OUT_PPTX)
    prs = Presentation(str(OUT_PPTX))

    # 表紙・目次のプレースホルダを埋める
