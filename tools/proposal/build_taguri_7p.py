# ── レイアウト定義 ────────────────────────────────────────────────
# 高さは本文の量から自動で決める（flow）。指定するのは x / w / 縦の並び順だけ。
# k: claim / label / card / arrow / fork / join / src / lanes / row


def card(t, b=None, num=None, style="plain", tpt=10.5, bpt=9.5):
    return dict(k="card", t=t, b=b, num=num, style=style, tpt=tpt, bpt=bpt)


def label(text):
    return dict(k="label", text=text, pt=9.5)


def bullets(items, pt=10.5):
    """箇条書き。枠で囲まず「・」を頭に付けた本文として出す。"""
    return para("\n".join("・" + t for t in items), pt=pt)


def group(title, items, gap=0.10):
    """内側の要素をまとめて枠で囲む。「ここからここまでがシステム内部」を示す。"""
    return dict(k="group", title=title, items=items, gap=gap)


def para(text, pt=10.5):
    """枠のない本文。図にしなくてよいものはこれで書く。"""
    return dict(k="para", text=text, pt=pt)


def src(text):
    return dict(k="src", text=text, pt=8.5)


def arrow(note=None, h=0.20, dirn="down"):
    return dict(k="arrow", note=note, h=h, dirn=dirn)


def dotgrid(total, hi, cols=88, dot=0.072, note=None):
    """点の格子。1 点 = 1 件。母数の大きさと、そこから選ばれる数を一目で見せる。"""
    return dict(k="dotgrid", total=total, hi=hi, cols=cols, dot=dot, note=note)


def bars(rows, unit="", pt=9.5, note=None, baseline=True, lead=None):
    """横棒の比較。rows は (ラベル, 値, 値の表示) の並び。

    帯の長さは最大値で正規化する（1 行目で正規化すると、1 行目より大きい行が
    枠の外まで伸びる）。baseline=True は 1 行目を「比較の基準」として淡く描く。
    分布のように行が対等な場合は baseline=False にする。
    lead は図から読み取ってほしい結論。注記（淡い 8.5pt）ではなく黒の太字で置く。
    """
    return dict(k="bars", rows=rows, unit=unit, pt=pt, note=note,
                baseline=baseline, lead=lead)


def table(cols, rows, widths=None, pt=9.5):
    """表。桁の揃った比較はこれで書く（全角スペースで揃えない）。

    cols   見出しの並び
    rows   各行のセル。列数は cols と同じ
    widths 列幅の比。省略すると均等
    """
    assert all(len(r) == len(cols) for r in rows), "列数が見出しと合っていない"
    return dict(k="table", cols=cols, rows=rows, widths=widths, pt=pt)


def cycle(nodes, center=None, h=2.75, nw=2.05, nh=0.60, note=None,
          entry=None, interlude=None, ring_w=None):
    """円形のサイクル図。nodes は (見出し, 本文) を 4 つ、時計回りに並べる。

    entry     円の上に置く箱の並び。[(見出し, 本文), ...] を横に並べ、合流して ① につなぐ
    interlude ④ と ① のあいだ（左上）に置く箱。循環の途中に入る手続き
    ring_w    楕円の幅。省略すると図の幅いっぱいに広がる
    """
    assert len(nodes) == 4, "サイクルの節点は 4 つに固定する"
    return dict(k="cycle", nodes=nodes, center=center, h=h, nw=nw, nh=nh, note=note,
                entry=entry, interlude=interlude, ring_w=ring_w)


def loopback(note, h=0.34, span=1.0):
    """左向きの戻り矢印。span は幅に対する割合で、右端から左へ伸ばす。

    戻り先が図の左端でないときは span を指定して、届く位置を合わせる。
    """
    return dict(k="loopback", note=note, h=h, span=span)


def stack(x, w, items, gap=0.09):
    return dict(x=x, w=w, items=items, gap=gap)


