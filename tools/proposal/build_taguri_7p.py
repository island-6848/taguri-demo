# ── 高さの計算と座標の解決 ──────────────────────────────────────
LH = 1.36          # 行送りの見積もり
LEAD_PT = 10.5     # 図から読み取ってほしい結論（黒・太字）の大きさ
PAD_W = 0.17       # 枠の左右余白（pptx の margin 0.08 x 2 + 余裕）
PAD_H = 0.13
GP_TOP, GP_X, GP_BOT = 0.30, 0.11, 0.12   # group の見出し／左右／下の余白
TB_PAD, TB_CELL = 0.06, 0.10              # 表の外側の余白／セルの上下余白


def note_h(note, w: float, pt: float = 8.5) -> float:
    """図の下に添える注記（8.5pt）の高さ。折り返した行数から出す。

    固定値にしていたため、2 行以上の注記が下の要素に重なっていた。枠の検査は
    項目の矩形しか見ないので、この重なりは検出できない。
    """
    if not note:
        return 0.0
    return wrapped_lines(note, pt, w) * (pt * LH / 72) + 0.06


def wrapped_lines(text: str, pt: float, w_in: float) -> int:
    """全角 1 文字 ≒ font pt として折り返し行数を見積もる。"""
    per_line = max(1, int((w_in - PAD_W) * 72 / pt))
    return sum(max(1, -(-len(para) // per_line)) for para in text.split("\n"))


def measure(it: dict, w: float) -> float:
    k = it["k"]
    if k == "claim":
        return wrapped_lines(it["text"], it["pt"], w - 0.14) * it["pt"] * LH / 72 + 0.06
    if k in ("label", "src"):
        return wrapped_lines(it["text"], it["pt"], w + 0.17) * it["pt"] * LH / 72 + 0.04
    if k == "para":
        return wrapped_lines(it["text"], it["pt"], w + 0.10) * it["pt"] * 1.55 / 72 + 0.06
    if k == "card":
        h = PAD_H
        if it.get("num"):
            h += 8.5 * LH / 72
        h += wrapped_lines(it["t"], it["tpt"], w) * it["tpt"] * LH / 72
        if it.get("b"):
            h += wrapped_lines(it["b"], it["bpt"], w) * it["bpt"] * LH / 72
        return h
    if k in ("arrow", "fork", "join", "loopback"):
        return it.get("h", 0.20)
    if k == "lanes":
        gap = it.get("gap", 0.20)
        n = len(it["lanes"])
        lw = (w - gap * (n - 1)) / n
        return max(stack_height(lane, lw) for lane in it["lanes"])
    if k == "group":
        return GP_TOP + stack_height(it["items"], w - 2 * GP_X,
                                     it.get("gap", 0.10)) + GP_BOT
    if k == "row":
        return max(measure(c[1], c[0]) for c in it["cells"])
    if k == "cycle":
        return (it["h"] + (0.82 if it["entry"] else 0.0)
                + (0.20 if it["note"] else 0.0))
    if k == "table":
        return TB_PAD + sum(table_row_h(it, r, w) for r in [it["cols"]] + it["rows"])
    if k == "dotgrid":
        pitch = w / it["cols"]
        nrow = -(-it["total"] // it["cols"])
        h = nrow * pitch
        return h + note_h(it.get("note"), w)
    if k == "bars":
        return (len(it["rows"]) * (it["pt"] * LH / 72 + 0.13)
                + note_h(it.get("lead"), w, LEAD_PT)
                + note_h(it.get("note"), w))
    raise ValueError(k)


def table_widths(it, w):
    n = len(it["cols"])
    ratio = it["widths"] or [1] * n
    total = sum(ratio)
    return [w * r / total for r in ratio]


def table_row_h(it, cells, w):
    """1 行の高さ。セルの中で最も折り返すものに合わせる。"""
    pt = it["pt"]
    ws = table_widths(it, w)
    lines = max(wrapped_lines(c, pt, ws[i]) for i, c in enumerate(cells))
    return lines * pt * LH / 72 + TB_CELL


def stack_height(items, w, gap=0.09) -> float:
    return sum(measure(it, w) for it in items) + gap * (len(items) - 1)


def place(items, x, w, y, gap, out):
    for it in items:
        h = measure(it, w)
        k = it["k"]
        if k == "lanes":
            n = len(it["lanes"])
            g = it.get("gap", 0.20)
            lw = (w - g * (n - 1)) / n
            for i, lane in enumerate(it["lanes"]):
                place(lane, x + i * (lw + g), lw, y, 0.09, out)
        elif k == "group":
            out.append(dict(it, x=x, y=y, w=w, h=h))
            place(it["items"], x + GP_X, w - 2 * GP_X, y + GP_TOP,
                  it.get("gap", 0.10), out)
        elif k == "row":
            cx = x
            for cw, cell in it["cells"]:
                ch = measure(cell, cw)
                # cell が group / lanes の場合もあるので place に委ねる
                place([cell], cx, cw, y + (h - ch) / 2, 0.0, out)
                cx += cw
        elif k == "cycle":
            out.append(dict(it, x=x, y=y, w=w, h=h))
        elif k == "loopback":
            sp = it.get("span", 1.0)
            out.append(dict(it, x=x + w * (1 - sp), y=y, w=w * sp, h=h))
        elif k in ("dotgrid", "bars"):
            out.append(dict(it, x=x, y=y, w=w, h=h))
        elif k == "table":
            ws = table_widths(it, w)
            heads = table_row_h(it, it["cols"], w)
            hs = [table_row_h(it, r, w) for r in it["rows"]]
            out.append(dict(it, x=x, y=y, w=w, h=TB_PAD + heads + sum(hs),
                            colw=ws, headh=heads, rowh=hs))
        else:
            out.append(dict(it, x=x, y=y, w=w, h=h))
        y += h + gap
    return y


def resolve(layout: dict) -> dict:
    shapes = []
    claim = dict(k="claim", text=layout["claim"], pt=13)
    ch = measure(claim, AREA_W)
    shapes.append(dict(claim, x=0, y=0, w=AREA_W, h=ch))
    tops = []
    for st in layout["stacks"]:
        y0 = ch + 0.14
        bottom = place(st["items"], st["x"], st["w"], y0, st.get("gap", 0.09), shapes)
        tops.append(bottom - st.get("gap", 0.09))
    return dict(no=layout["no"], title=layout["title"], shapes=shapes, bottom=max(tops))


def check_drawn(path) -> list[str]:
    """生成した pptx の図形が本文領域を出ていないかを検査する。

    check() は DSL の項目の枠だけを見るので、項目の内側で描く帯や点の長さが
    枠を超えても気づけない（実際に横棒が右にはみ出した）。描いた結果を測る。
    """
    prs = Presentation(str(path))
    problems = []
    for i, slide in enumerate(prs.slides, 1):
        for sh in slide.shapes:
            if sh.left is None or sh.width is None:
                continue
            right = (sh.left + sh.width) / 914400
            if right > AREA_X + AREA_W + 0.02:
                name = (sh.text_frame.text[:20].replace("\n", "/")
                        if sh.has_text_frame and sh.text_frame.text else sh.shape_type)
                problems.append(f"{i} 枚目: 右に {right - AREA_X - AREA_W:.2f}in はみ出し（{name}）")
    return problems


def check(resolved) -> list[str]:
    problems = []
    for r in resolved:
        chars = sum(len(sh.get("text", "") or "") + len(sh.get("t", "") or "")
                    + len(sh.get("b", "") or "") for sh in r["shapes"])
        room = AREA_H - r["bottom"]
        mark = "OK " if room >= -0.005 else "NG "
        print(f"  {mark}{r['title']}: {chars} 字 / 下端 {r['bottom']:.2f}in "
              f"（余り {room:+.2f}in）")
        if room < -0.005:
            problems.append(f"{r['title']}: {-room:.2f}in はみ出し")
        for sh in r["shapes"]:
            if sh["x"] + sh["w"] > AREA_W + 0.005:
                problems.append(f"{r['title']}: 右にはみ出し {sh.get('t') or sh['k']}")
    return problems


