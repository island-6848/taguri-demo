#!/usr/bin/env python3
"""クレジットの読み取り（`measure_nets.parse_credits` / `_names`）の検査。

    python3 tools/review/test_measure_nets.py

起案者の報告（2026-08-26）── 「The show! マレーネ…のやつでポスターと出演者を手で入れる、
のところで名簿に 4 人書いているのに、3 人しか反映されていないのはなぜ？」。

**「演出」「脚本」欄に【役職】タグを付けた名前を書くと、名前ごと消えていた。**
`_BRACKET` はスタッフ欄の「【役職】名前」を扱うために足したものだが、出演・脚本・演出の
3 欄は `_names()` を直接呼ぶので通らず、`_ROLE_PREFIX`（括弧の付かない役職しか剥がせない）
が素通しした角括弧が、名前を消す安全策（`"[【】［］《》]"` を含む語は捨てる）に当たって
名前ごと落ちていた。
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "review"))
sys.path.insert(0, str(ROOT / "tools" / "taguri"))
import measure_nets as MN                                          # noqa: E402
import app as APP                                                  # noqa: E402

ok = fail = 0


def check(name: str, cond: bool, got=None) -> None:
    global ok, fail
    if cond:
        ok += 1
        print(f"  OK  {name:<52} {got if got is not None else ''}")
    else:
        fail += 1
        print(f"  NG  {name:<52} ← {got!r}")


# ---------------------------------------------------------------- 実際に起きた例
# 「The Show！「マレーネ・ディートリヒ」東京公演」で本人が入れた 4 名（前田美波里・
# 作り手24・笹部博司・赤坂麻里）。演出と脚本は【】タグ付きで書いてある。
REAL = {"出演": "前田美波里\n作り手24（劇団2）",
        "演出": "【演出】 笹部博司",
        "脚本": "【台本】 笹部博司",
        "スタッフ": "【振付・ステージング】 赤坂麻里"}

check("【演出】タグ付きの名前が消えずに読める",
      MN._names(REAL["演出"]) == ["笹部博司"], MN._names(REAL["演出"]))
check("【台本】タグ付きの名前も読める（役職の語彙に無い語でも）",
      MN._names(REAL["脚本"]) == ["笹部博司"], MN._names(REAL["脚本"]))
check("スタッフ欄の【役職】書式は元から読めていた（回帰していないことの確認）",
      MN._names("赤坂麻里") == ["赤坂麻里"])

got = MN.parse_credits(REAL)
people = {p for _r, p in got}
check("4 人全員が名簿に入る", people == {"前田美波里", "作り手24", "笹部博司", "赤坂麻里"},
      sorted(people))
check("演出と脚本を兼ねる人は、役職ごとに別の組として残る（1 人が消えたことにしない）",
      ("演出", "笹部博司") in got and ("脚本", "笹部博司") in got, got)

# ---------------------------------------------------------------- 表示する人数
# **数えるのは人であって、(役職, 人) の組ではない。** 演出と脚本を兼ねる 1 人を
# 2 人と数えると、「4 名入れたのに 5 名と出る」という別の食い違いになる。
n = APP.hand_credit_count(REAL)
check("「◯名」は人数で数える（4 人 → 4、5 ではない）", n == 4, n)

# ---------------------------------------------------------------- 壊していないことの確認
check("普通の名前（角括弧なし）はそのまま読める",
      MN._names("前田美波里") == ["前田美波里"])
check("役職の語彙そのものは名前として読まない",
      MN._names("演出") == [])
check("角括弧の中身だけ（名前が続かない）は読まない",
      MN._names("【演出】") == [])
check("既存のスタッフ欄の複数【役職】名前も崩れていない",
      MN.parse_credits({"スタッフ": "【美術】山田太郎\n【照明】鈴木一郎"})
      == [("照明", "鈴木一郎"), ("美術", "山田太郎")])

# 役職の語は区切りがあるときだけ外す（2026-10-16）。「作」で始まる名前を削らない
check("「作」で始まる名前は削らない（作間龍斗）", MN._names("作間龍斗") == ["作間龍斗"], MN._names("作間龍斗"))
check("「作=名前」「演出=名前」の = も区切り", MN._names("作=唐十郎") == ["唐十郎"] and MN._names("演出=久保井研") == ["久保井研"],
      (MN._names("作=唐十郎"), MN._names("演出=久保井研")))

# 名前の代わりに書かれた案内の文と URL は人ではない（起案者の指示 2026-10-18「出演 スタッフ欄をご覧ください。になってる
# 箇所があるから直して」、fix-credit-guide-text）。「未定」は欄の全体のときだけ、ドメインは英数字のものだけ
for text in ("スタッフ欄をご覧ください。", "詳細は公式サイトにて、https://musical-za.co.jp/", "下記に掲載", "（後日発表）",
             "ComingSoon", "comigsoon", "下記スタッフ欄をご参照ください", "日により出演者が異なります、詳細はタイムテーブル欄をご覧ください。", "未定"):
    check(f"案内の文は名前ではない: {text}", MN._names(text) == [], MN._names(text))
check("名前の一部の「未定」・団体名の .com は名前のまま", MN._names("今井未定、演劇ユニットG.com") == ["今井未定", "演劇ユニットG.com"],
      MN._names("今井未定、演劇ユニットG.com"))
check("出演欄が案内の文だけなら、出演の人はいない",
      MN.parse_credits({"出演": "スタッフ欄をご覧ください。", "スタッフ": "演出：演出家甲"}) == [("演出", "演出家甲")])

# 所属（名前の後ろのカッコ）。起案者の指示 2026-10-19「所属の表をつくって」（dec-affiliation-table）
got = MN.affiliations("井田真裕（お庭のなまたまご）、鎌塚慎平(劇団・木製ボイジャー14号)、正門良規(Aぇ!group、関西ジャニーズJr.)、"
                      "佐藤 花子（劇団甲主宰）、宮地綾")
check("名前（所属）を (名前, 所属) に。中黒は割らず、「、」は複数の所属、主宰は外す", got == [
    ("井田真裕", "お庭のなまたまご"), ("鎌塚慎平", "劇団・木製ボイジャー14号"), ("正門良規", "Aぇ!group"),
    ("正門良規", "関西ジャニーズJr."), ("佐藤花子", "劇団甲")], got)
for text in ("山田太郎（Wキャスト）", "山田太郎（12/20）", "山田太郎（石川、新潟公演）", "山田太郎（ピアノ）", "山田太郎（ソプラノ）",
             "山田太郎（プリンシパル）", "山田太郎（客演）", "山田太郎（フリー）", "山田太郎（元劇団乙）", "山田太郎（文学座を経て）",
             "山田太郎（大阪）", "山田太郎（10歳）", "山田太郎（以上、交互出演）", "山田太郎（Aチーム）"):
    check(f"所属ではないカッコは拾わない: {text}", MN.affiliations(text) == [], MN.affiliations(text))
check("どちらの人の所属か決められないときは付けない", MN.affiliations("甲野一郎・乙野二郎（劇団丙）") == [("乙野二郎", "劇団丙")],
      MN.affiliations("甲野一郎・乙野二郎（劇団丙）"))

check("所属の束ねる鍵: 記号・空白・会社の種類・頭の劇団を落とす",
      len({MN.affil_key(x) for x in ("劇団青年座", "青年座")}) == 1
      and len({MN.affil_key(x) for x in ("流山児★事務所", "流山児☆事務所", "株式会社流山児★事務所")}) == 1
      and len({MN.affil_key(x) for x in ("LE VELVETS", "LEVELVETS", "LeVelvets")}) == 1)
check("劇団EXILE と EXILE は束ねない", MN.affil_key("劇団EXILE") != MN.affil_key("EXILE"))
check("頭の語を除くと 1 字しか残らないものは束ねない", MN.affil_key("劇団森") != MN.affil_key("森"))

print(f"{ok} 件通過・{fail} 件失敗")
sys.exit(1 if fail else 0)
